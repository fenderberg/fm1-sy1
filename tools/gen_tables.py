#!/usr/bin/env python3
"""Generate app/dsp/s1_tables.{h,c} from the measured tables of oxo_synth2 (MIT).

Usage: tools/gen_tables.py PATH/TO/oxo_synth2

The tables are measurements of the original Synth1's parameter laws, published
under the MIT licence by Francois Chabloz (github.com/chab/oxo_synth2). See
THIRD_PARTY.md. Only the tables the FM-1 engine uses are taken.
"""
import re
import sys
from pathlib import Path

MEASURED = [  # (source name, C name, C type)
    ("kAmpAttackSeconds", "s1_t_attack_s", "float"),
    ("kEnvTauSeconds", "s1_t_env_tau_s", "float"),
    ("kAmpSustainLevel", "s1_t_amp_sustain", "float"),
    ("kAmpGain", "s1_t_amp_gain", "float"),
    ("kOsc2PitchSemis", "s1_t_osc2_semis", "int8_t"),
    ("kFineCents", "s1_t_fine_cents", "int8_t"),
    ("kFmBeta", "s1_t_fm_beta", "float"),
    ("kLadderCutoffHz", "s1_t_ladder_hz", "float"),
    ("kLadderFeedbackComp", "s1_t_ladder_comp", "float"),
    ("kSaturationA", "s1_t_sat_a", "float"),
    ("kKbdTrack", "s1_t_kbd_track", "float"),
    ("kLfoPitchCents", "s1_t_lfo_cents", "float"),
    ("kUnisonDetuneCents", "s1_t_unison_cents", "float"),
    ("kEqToneHz", "s1_t_eq_tone_hz", "float"),
    ("kDelayToneHz", "s1_t_delay_tone_hz", "float"),
    ("kPortaTau", "s1_t_porta_tau", "float"),
    ("kFilterVelScale", "s1_t_filter_vel", "float"),
    ("kAd1Drive", "s1_t_ad1_drive", "float"),
    ("kAd1Out", "s1_t_ad1_out", "float"),
    ("kAd2Drive", "s1_t_ad2_drive", "float"),
    ("kAd2Curve", "s1_t_ad2_curve", "float"),
    ("kDdSlope", "s1_t_dd_slope", "float"),
    ("kDdPeak", "s1_t_dd_peak", "float"),
]


def array(text, name):
    m = re.search(r"\b" + name + r"\[(\d+)\]\s*=\s*\{(.*?)\};", text, re.S)
    if not m:
        sys.exit("table not found: " + name)
    body = re.sub(r"//.*", "", m.group(2))
    vals = [v.strip().rstrip("fF") for v in body.split(",") if v.strip()]
    if len(vals) != int(m.group(1)):
        sys.exit("%s: %d values, expected %s" % (name, len(vals), m.group(1)))
    return vals


def emit(out, ctype, cname, vals):
    out.append("const %s %s[%d] = {" % (ctype, cname, len(vals)))
    suffix = "f" if ctype == "float" else ""
    for i in range(0, len(vals), 8):
        row = []
        for v in vals[i:i + 8]:
            if ctype == "float":
                v = repr(float(v))
            row.append(v + suffix)
        out.append("    " + ", ".join(row) + ",")
    out.append("};")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    core = Path(sys.argv[1]) / "EngineCore"
    measured = (core / "MeasuredTables.hpp").read_text()
    params = (core / "Params.hpp").read_text()
    legacy = (core / "LegacyTables.hpp").read_text()
    root = Path(__file__).resolve().parent.parent / "app" / "dsp"

    h = ["/* GENERATED by tools/gen_tables.py. Do not edit.",
         " * Measured Synth1 parameter laws from oxo_synth2 (MIT, (c) 2026 Francois Chabloz). */",
         "#pragma once", "#include <stdint.h>", ""]
    c = [h[0], h[1], '#include "s1_tables.h"', ""]

    for src, cname, ctype in MEASURED:
        vals = array(measured, src)
        h.append("extern const %s %s[%d];" % (ctype, cname, len(vals)))
        emit(c, ctype, cname, vals)

    # parameter ranges and the original's init values
    rows = re.findall(r'\{"(\w+)",\s*"([^"]+)",\s*(-?\d+),\s*(-?\d+),\s*(-?\d+),\s*(?:true|false)\}', params)
    rows = rows[:99]
    if len(rows) != 99:
        sys.exit("expected 99 parameters, found %d" % len(rows))
    h += ["", "#define S1_NPARAMS 99", "enum {"]
    for i, r in enumerate(rows):
        h.append("    S1P_%s = %d," % (r[0].upper(), i))
    h += ["};", "extern const int32_t s1_param_min[S1_NPARAMS], s1_param_max[S1_NPARAMS], s1_param_def[S1_NPARAMS];",
          "extern const char *const s1_param_name[S1_NPARAMS];"]
    for k, idx in (("min", 2), ("max", 3), ("def", 4)):
        emit(c, "int32_t", "s1_param_%s" % k, [r[idx] for r in rows])
    c.append("const char *const s1_param_name[S1_NPARAMS] = {")
    for r in rows:
        c.append('    "%s",' % r[1])
    c.append("};")

    # old patch versions (ver < 109): remap tables and rules
    m = re.search(r"kTables\[13\]\[128\]\s*=\s*\{(.*?)\n\};", legacy, re.S)
    tabs = re.findall(r"\{([^{}]*)\}", m.group(1))
    if len(tabs) != 13:
        sys.exit("expected 13 legacy tables")
    c.append("const uint8_t s1_legacy_tab[13][128] = {")
    for t in tabs:
        vals = [v.strip() for v in t.split(",") if v.strip()]
        if len(vals) != 128:
            sys.exit("legacy table size")
        c.append("    {" + ", ".join(vals) + "},")
    c.append("};")
    m = re.search(r"kRules\[\]\s*=\s*\{(.*?)\n\};", legacy, re.S)
    rules = re.findall(r"\{(\d+),\s*(-?\d+),\s*(-?\d+),\s*([^}]+)\}", m.group(1))
    grp = {"kVer100": 1, "kVer105": 2, "kVer107": 4}
    c.append("const s1_legacy_rule s1_legacy_rules[%d] = {" % len(rules))
    for p, t, v, g in rules:
        mask = sum(grp[x.strip()] for x in g.split("|"))
        c.append("    {%s, %s, %s, %d}," % (p, t, v, mask))
    c.append("};")
    h += ["", "typedef struct { int8_t param, table; int32_t value; uint8_t groups; } s1_legacy_rule;",
          "#define S1_LEGACY_NRULES %d" % len(rules),
          "extern const uint8_t s1_legacy_tab[13][128];",
          "extern const s1_legacy_rule s1_legacy_rules[S1_LEGACY_NRULES];"]

    (root / "s1_tables.h").write_text("\n".join(h) + "\n")
    (root / "s1_tables.c").write_text("\n".join(c) + "\n")
    print("wrote", root / "s1_tables.h", "and s1_tables.c")

    # the same parameter ranges and old-version rules for the emulator page's patch loader (app/web/emu/app.js),
    # between its two marker lines
    page = root.parent / "web" / "emu" / "app.js"
    if page.exists():
        import json
        data = {
            "min": [int(r[2]) for r in rows], "max": [int(r[3]) for r in rows], "def": [int(r[4]) for r in rows],
            "legacyTab": [[int(v) for v in t.split(",") if v.strip()] for t in tabs],
            "legacyRules": [[int(p), int(t), int(v), sum(grp[x.strip()] for x in g.split("|"))] for p, t, v, g in rules],
        }
        block = ("// <tables> GENERATED by tools/gen_tables.py from oxo_synth2 (MIT). Do not edit.\n"
                 "const T = " + json.dumps(data, separators=(",", ":")) + ";\n// </tables>")
        text = page.read_text()
        new = re.sub(r"// <tables>.*?// </tables>", lambda m: block, text, flags=re.S)
        if new == text and block not in text:
            sys.exit("%s: no // <tables> ... // </tables> region" % page)
        page.write_text(new)
        print("wrote the tables in", page)


if __name__ == "__main__":
    main()
